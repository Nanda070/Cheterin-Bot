interface DocSection {
  id: string
  title: string
  group: string
  content: ReactNode
}

function H(props: { children: ReactNode }) {
  return <h2 className="mt-6 text-base font-semibold text-foreground first:mt-0">{props.children}</h2>
}

function H3(props: { children: ReactNode }) {
  return <h3 className="mt-4 text-sm font-semibold text-foreground">{props.children}</h3>
}

function P(props: { children: ReactNode }) {
  return <p className="mt-2 text-sm leading-relaxed text-muted">{props.children}</p>
}

function UL(props: { children: ReactNode }) {
  return <ul className="mt-2 flex list-disc flex-col gap-1 pl-5 text-sm leading-relaxed text-muted">{props.children}</ul>
}

function OL(props: { children: ReactNode }) {
  return <ol className="mt-2 flex list-decimal flex-col gap-1 pl-5 text-sm leading-relaxed text-muted">{props.children}</ol>
}

function Code(props: { children: ReactNode }) {
  return <code className="rounded bg-surface-hover px-1.5 py-0.5 text-xs text-foreground">{props.children}</code>
}

function Pre(props: { children: string }) {
  return (
    <pre className="mt-2 overflow-x-auto rounded-control border border-border bg-background p-3 text-xs leading-relaxed text-foreground">
      {props.children}
    </pre>
  )
}

function Note(props: { children: ReactNode }) {
  return (
    <div className="mt-3 rounded-control border border-primary/40 bg-primary-muted p-3 text-sm leading-relaxed text-foreground">
      {props.children}
    </div>
  )
}

function Warn(props: { children: ReactNode }) {
  return (
    <div className="mt-3 rounded-control border border-warning/40 bg-warning/10 p-3 text-sm leading-relaxed text-foreground">
      {props.children}
    </div>
  )
}

function Table(props: { headers: string[]; rows: ReactNode[][] }) {
  return (
    <div className="mt-3 overflow-x-auto">
      <table className="w-full min-w-120 border-collapse text-sm">
        <thead>
          <tr className="border-b border-border text-left text-muted">
            {props.headers.map((h) => (
              <th key={h} className="py-2 pr-4 font-medium">
                {h}
              </th>
            ))}
          </tr>
        </thead>
        <tbody>
          {props.rows.map((row, i) => (
            <tr key={i} className="border-b border-border last:border-b-0 align-top">
              {row.map((cell, j) => (
                <td key={j} className={`py-2 pr-4 ${j === 0 ? 'whitespace-nowrap text-foreground' : 'text-muted'}`}>
                  {cell}
                </td>
              ))}
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  )
}

